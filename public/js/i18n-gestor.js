/* =====================================================================
   Idiomas do painel do gestor: português (pt), inglês (en) e
   espanhol (es).

   O idioma fica no localStorage "idioma" (a mesma chave usada pela aba
   de triagem por voz, gestor-voz.js, e pela página inicial). Com sessão
   aberta, gestor.js também grava o idioma no servidor
   (POST /api/gestor/idioma), que é o idioma dos e-mails do gestor.
   Sem nada salvo, o painel abre em português; no login, se o navegador
   ainda não tem idioma salvo, vale o idioma salvo no servidor.

   Uso: tg(chave, { variavel: valor }) devolve o texto no idioma atual;
   tgn(chave, n) escolhe a forma singular (chave_1) quando n = 1.
   Os textos dos testes (data.js) são trocados por aplicarIdiomaDados().
   Conteúdo escrito pela empresa (vagas, cargos, competências, questões,
   anotações) vem da API e não é traduzido.
   ===================================================================== */

