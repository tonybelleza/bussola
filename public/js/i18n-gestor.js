// ------------------------------------------------ detecção do idioma
function normalizarIdiomaGestor(v) {
  const cod = String(v || "").trim().toLowerCase().slice(0, 2);
  return IDIOMAS_GESTOR.includes(cod) ? cod : "";
}

// idioma salvo neste navegador (vazio se nada foi escolhido ainda)
function idiomaGestorSalvo() {
  try { return normalizarIdiomaGestor(localStorage.getItem("idioma")); } catch (e) { return ""; }
}

let idiomaGestor = idiomaGestorSalvo() || "pt";

// ------------------------------------------------ tradução
function tg(chave, vars) {
  const dic = I18N_GESTOR[idiomaGestor] || I18N_GESTOR.pt;
  let s = dic[chave];
  if (s === undefined) s = I18N_GESTOR.pt[chave];
  if (s === undefined) return chave;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

// plural simples: usa "chave_1" quando n = 1 (se existir)
function tgn(chave, n, vars) {
  const dic = I18N_GESTOR[idiomaGestor] || I18N_GESTOR.pt;
  const k = n === 1 && dic[chave + "_1"] !== undefined ? chave + "_1" : chave;
  return tg(k, Object.assign({ n: fmtNum(n) }, vars || {}));
}

// ------------------------------------------------ formatos por idioma
function localeGestor() {
  return LOCALE_GESTOR[idiomaGestor] || "pt-BR";
}

function fmtNum(n, casas) {
  const v = Number(n);
  if (n === null || n === undefined || n === "" || isNaN(v)) return n == null ? "" : String(n);
  const op = casas != null ? { minimumFractionDigits: casas, maximumFractionDigits: casas } : {};
  return v.toLocaleString(localeGestor(), op);
}

// datas do servidor: "AAAA-MM-DD HH:MM:SS" em UTC (datetime('now') do SQLite)
function lerDataServidor(texto) {
  const s = String(texto || "").trim();
  if (!s) return null;
  if (/^\d{4}-\d{2}-\d{2}$/.test(s)) {
    const [a, m, d] = s.split("-").map(Number);
    return new Date(a, m - 1, d);
  }
  const iso = s.replace(" ", "T");
  const d = new Date(/[zZ]|[+-]\d{2}:?\d{2}$/.test(iso) ? iso : iso + "Z");
  return isNaN(d.getTime()) ? null : d;
}

function fmtData(texto) {
  const d = lerDataServidor(texto);
  if (!d) return String(texto || "").slice(0, 10);
  return d.toLocaleDateString(localeGestor(), { day: "2-digit", month: "2-digit", year: "numeric" });
}

function fmtDataHora(texto) {
  const d = lerDataServidor(texto);
  if (!d) return String(texto || "").slice(0, 16).replace("T", " ");
  return d.toLocaleString(localeGestor(), {
    day: "2-digit", month: "2-digit", year: "numeric", hour: "2-digit", minute: "2-digit",
  });
}

// "2026-10" vira "out. de 2026" / "Oct 2026" / "oct 2026"
function fmtMes(texto) {
  const m = String(texto || "").match(/^(\d{4})-(\d{2})$/);
  if (!m) return String(texto || "");
  return new Date(Number(m[1]), Number(m[2]) - 1, 1)
    .toLocaleDateString(localeGestor(), { month: "short", year: "numeric" });
}

// ------------------------------------------------ nomes traduzidos de valores fixos
function nomeEtapa(etapa, reserva) {
  const k = "et_" + etapa;
  return I18N_GESTOR.pt[k] !== undefined ? tg(k) : (reserva || etapa);
}

function nomeStatusVaga(status) {
  const k = "status_" + status;
  return I18N_GESTOR.pt[k] !== undefined ? tg(k) : status;
}

function nomeNivelCargo(nivel) {
  const k = CHAVES_NIVEIS_CARGO[nivel];
  return k ? tg(k) : nivel;
}

function nomePaisGestor(p) {
  return (typeof PAISES_NOMES !== "undefined" && PAISES_NOMES[p]) || p;
}

// nome de um modelo de e-mail: o servidor manda em português
// ("Confirmação de inscrição (EN)"); aqui o nome sai da chave base
function nomeTemplate(chave, nomeServidor) {
  let base = chave;
  let sufixo = "";
  const m = chave.match(/^(.+)_(en|es|pt)$/);
  if (m) { base = m[1]; sufixo = " (" + m[2].toUpperCase() + ")"; }
  if (base === "confirmacao" || base === "lembrete") return tg("tpl_" + base) + sufixo;
  if (base === "voz_convite" && m) return tg("tpl_voz_convite", { idioma: tg("lingua_" + m[2]) });
  const et = base.match(/^etapa_(.+)$/);
  if (et && ETAPAS_GESTOR.includes(et[1])) return tg("tpl_etapa", { etapa: nomeEtapa(et[1]) }) + sufixo;
  return nomeServidor || chave;
}

// ------------------------------------------------ troca de idioma
function aplicarTextosEstaticosGestor() {
  document.querySelectorAll("[data-i18n-g]").forEach((el) => {
    el.textContent = tg(el.dataset.i18nG);
  });
}

// troca o idioma da página (sem redesenhar a tela: gestor.js cuida disso)
function definirIdiomaGestor(lang, salvar) {
  const cod = normalizarIdiomaGestor(lang) || "pt";
  idiomaGestor = cod;
  if (salvar !== false) {
    try { localStorage.setItem("idioma", cod); } catch (e) { /* armazenamento bloqueado */ }
  }
  document.documentElement.lang = LANG_HTML_GESTOR[cod];
  if (typeof aplicarIdiomaDados === "function") aplicarIdiomaDados(cod);
  // a aba de voz (gestor-voz.js) tem a própria variável de idioma
  if (typeof vozIdioma !== "undefined") vozIdioma = cod;
  aplicarTextosEstaticosGestor();
  document.querySelectorAll(".seletor-idioma button").forEach((b) => {
    b.classList.toggle("ativo", b.dataset.lang === cod);
    b.setAttribute("aria-pressed", b.dataset.lang === cod ? "true" : "false");
  });
  const caixa = document.querySelector(".seletor-idioma");
  if (caixa) caixa.setAttribute("aria-label", tg("idioma"));
}

// seletor PT / EN / ES na barra superior; aoTrocar(lang) faz o resto
function montarSeletorIdiomaGestor(aoTrocar) {
  if (!document.getElementById("estilo-seletor-idioma")) {
    const estilo = document.createElement("style");
    estilo.id = "estilo-seletor-idioma";
    estilo.textContent =
      ".seletor-idioma{display:inline-flex;border:1px solid var(--line);border-radius:999px;overflow:hidden;margin-right:6px;flex-shrink:0}" +
      ".seletor-idioma button{background:none;border:0;color:var(--text-2);font:inherit;font-size:.72rem;font-weight:600;letter-spacing:.05em;padding:6px 9px;cursor:pointer;line-height:1}" +
      ".seletor-idioma button:hover{color:var(--text)}" +
      ".seletor-idioma button.ativo{background:var(--surface-2);color:var(--text)}";
    document.head.appendChild(estilo);
  }
  const acoes = document.querySelector(".topbar .actions");
  if (!acoes || acoes.querySelector(".seletor-idioma")) return;
  const caixa = document.createElement("div");
  caixa.className = "seletor-idioma";
  caixa.setAttribute("role", "group");
  caixa.setAttribute("aria-label", tg("idioma"));
  caixa.innerHTML = IDIOMAS_GESTOR.map((cod) =>
    `<button type="button" data-lang="${cod}" title="${NOMES_IDIOMAS_GESTOR[cod]}">${cod.toUpperCase()}</button>`
  ).join("");
  acoes.insertBefore(caixa, acoes.firstChild);
  caixa.querySelectorAll("button").forEach((b) =>
    b.addEventListener("click", () => {
      if (b.dataset.lang === idiomaGestor) return;
      if (aoTrocar) aoTrocar(b.dataset.lang);
      else definirIdiomaGestor(b.dataset.lang);
    })
  );
  definirIdiomaGestor(idiomaGestor, false);
}

