function normalizarIdiomaLanding(v) {
  const cod = String(v || "").trim().toLowerCase().slice(0, 2);
  return IDIOMAS_LANDING.includes(cod) ? cod : "";
}

function idiomaAtual() {
  let salvo = "";
  try { salvo = normalizarIdiomaLanding(localStorage.getItem("idioma")); } catch (e) { /* armazenamento bloqueado */ }
  if (salvo) return salvo;
  const n = String(navigator.language || "").toLowerCase();
  if (n.startsWith("pt")) return "pt";
  if (n.startsWith("es")) return "es";
  return "en";
}
